// Regenerates precache-list.js: every file the app needs offline, plus a content
// hash used as the cache version. Run after adding/changing files:  npm run precache
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join, relative, resolve } from 'node:path';

const ROOT = resolve(new URL('..', import.meta.url).pathname);
const INCLUDE_DIRS = ['css', 'src', 'vendor', 'icons'];
const INCLUDE_FILES = ['index.html', 'manifest.webmanifest'];
const EXT = /\.(js|css|html|svg|png|webmanifest|json)$/;

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (EXT.test(e.name)) out.push(p);
  }
  return out;
}

export async function listAppFiles() {
  const files = [...INCLUDE_FILES.map((f) => join(ROOT, f))];
  for (const d of INCLUDE_DIRS) files.push(...(await walk(join(ROOT, d))));
  return files.map((f) => relative(ROOT, f).split('\\').join('/')).sort();
}

export async function buildPrecache() {
  const files = await listAppFiles();
  const hash = createHash('sha256');
  for (const f of files) { hash.update(f); hash.update(await readFile(join(ROOT, f))); }
  const version = hash.digest('hex').slice(0, 12);
  const body = `// Generated by tools/gen-precache.mjs. Do not edit by hand.\nself.PRECACHE_VERSION = '${version}';\nself.PRECACHE = ${JSON.stringify(['./', ...files.map((f) => `./${f}`)], null, 1)};\n`;
  return { files, version, body };
}

if (resolve(process.argv[1] || '') === resolve(new URL(import.meta.url).pathname)) {
  const { files, version, body } = await buildPrecache();
  await writeFile(join(ROOT, 'precache-list.js'), body);
  console.log(`precache-list.js: ${files.length} files, version ${version}`);
}
